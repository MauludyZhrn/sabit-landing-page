std::string Translator::tr_std(const std::string& key) const {
    const auto& dict = (current_lang_ == Language::Indonesian) ? id_dict_ : en_dict_;
    auto it = dict.find(key);
    if (it != dict.end()) {
        return it->second;
    }
    return key;
}

QString Translator::tr(const std::string& key) const {
    const auto& dict = (current_lang_ == Language::Indonesian) ? id_dict_ : en_dict_;
    auto it = dict.find(key);
    if (it != dict.end()) {
        return QString::fromStdString(it->second);
    }
    return QString::fromStdString(key);
}

